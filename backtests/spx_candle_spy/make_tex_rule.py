"""Write the paper fragment for the rule now in use from rule_summary.json (no hand-typed numbers).

Run from the repository root, after rule_trades.py:
  .venv/bin/python -I backtests/spx_candle_spy/make_tex_rule.py
Writes papers/spx_candle_1550/rule_section_draft.tex.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
S = json.load(open(ROOT / "backtests/spx_candle_spy/rule_summary.json"))
OUT = ROOT / "papers/spx_candle_1550/rule_section_draft.tex"


def usd(x, n=0):
    return f"${'+' if x >= 0 else '-'}\\dollar{abs(x):,.{n}f}$".replace(",", "{,}")


def plain(x, n=0):
    return f"\\dollar{abs(x):,.{n}f}".replace(",", "{,}")


rows = []
for y, v in S["by_year"].items():
    rows.append(f"{y} & {v['sessions']} & {v['trades']} & {100 * v['share_of_sessions']:.0f}\\% & {usd(v['per_trade'])} & {usd(v['total'])} & {v['won']} \\\\")
tot_sess = sum(v["sessions"] for v in S["by_year"].values())
rows.append("\\midrule")
rows.append(f"All & {tot_sess:,} & {S['trades']} & {100 * S['trades'] / tot_sess:.0f}\\% & {usd(S['per_trade'])} & {usd(S['total'])} & "
            f"{sum(v['won'] for v in S['by_year'].values())} \\\\".replace(",", "{,}"))
year_rows = "\n".join(rows)
d, r, a = S["dropped"], S["recent"], S["after_backtest"]
late = [v for y, v in S["by_year"].items() if y >= "2023"]
bs = a.get("by_source", {})
parts = []
if "broker" in bs:
    parts.append(f"{bs['broker']['trades']} priced from the collector's one-minute broker bars made {usd(bs['broker']['total'])}")
if "Databento" in bs:
    parts.append(f"{bs['Databento']['trades']} priced from OPRA asks bought afterwards made {usd(bs['Databento']['total'])}")
unpriced = a["signal_days"] - a["priced"]
after_txt = ("were too few to mean anything: " + " and ".join(parts) + (f"; {unpriced} have no price on file" if unpriced else "")
             + f", {usd(a['total'])} in all with {a['won']} of {a['priced']} profitable.")

tex = f"""% Draft addition to the SPY-candle section of main.tex: the rule now in use, as a description.
% GENERATED by backtests/spx_candle_spy/make_tex_rule.py from backtests/spx_candle_spy/rule_summary.json
% (written by rule_trades.py). Do not edit numbers by hand; re-run the two scripts. Macros used: \\dollar, \\ITM.
% Descriptive, NOT pre-registered: the intersection of two cells of the registered SPY study, computed after its run.
% Period 2021-01-01..2026-10-20; "recent" = {r['since']}..{r['to']}; later days {a['from']}..{a['to']}.

\\paragraph{{The rule now in use (descriptive).}} After the SPY study the live alert was changed to act on one rule
built from its lines: the SPY 15:50 candle in its band of 70\\% or more, and the index candle at 60\\% or more in the
same direction; \\ITM{{10}} in that direction at the 15:51 ask, held to settlement. This is the intersection of two
cells the study reported, not a registered line of its own, and it is nearly the 70\\% band itself: of that band's
{S['source_trades_spy_70']} trades, {d['no index bar']} had no index bar and {d['index candle under 60%']} had an index candle below
60\\%, which leaves {S['trades']}. On 2021-01-01 to 2026-10-20 those trades made {usd(S['per_trade'], 2)} each and
{usd(S['total'])} in all, with {100 * S['won']:.1f}\\% profitable, an average gain of {plain(S['avg_win'])} against an
average loss of {plain(abs(S['avg_loss']))}, a worst trade of {usd(S['worst'])}, a longest run of
{S['longest_losing_streak']} losing trades and a worst peak-to-trough decline of {plain(S['worst_peak_to_trough'])}
(Table~\\ref{{tab:rulenow}}). The rule traded on about {100 * sum(v['trades'] for v in late) / sum(v['sessions'] for v in late):.0f}\\%
of sessions once expiries became daily. These figures describe days that helped to shape the rule, with the entry
at the instant the candle closes, and they are not evenly spread: from {r['since']} to {r['to']}, the last ten weeks
of the sample, the rule lost {plain(abs(r['total']))} over {r['trades']} trades, {r['won']} of them profitable. The
{a['signal_days']} signal days after the sample ({a['from']} to {a['to']}) {after_txt} The alert now sends two messages a session, whether the candles look like arming at about 15:50:40
and the decision right after 15:51:00, and logs every session's three candles and the outcome.

\\begin{{table}}[h]
\\centering
\\small
\\caption{{The rule now in use, by year: SPY 15:50 candle of 70\\% or more and index candle of 60\\% or more in the same
direction, \\ITM{{10}} at the 15:51 ask, held to settlement, one contract. Sessions are full sessions; expiries were
not daily before 2022. Descriptive; not a registered line.}}
\\label{{tab:rulenow}}
\\begin{{tabular}}{{@{{}}lrrrrrr@{{}}}}
\\toprule
Year & Sessions & Trades & Share & \\$/trade & Total & Won \\\\
\\midrule
{year_rows}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""
OUT.write_text(tex)
print("wrote", OUT, len(tex), "chars")
